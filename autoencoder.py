"""
===============================================================================
Smart Refrigerator Temperature Anomaly Detection using IoT and DNN
-------------------------------------------------------------------------------
File: autoencoder.py
Phase 3: Autoencoder Neural Network Baseline Anomaly Detection
Description:
    This script builds, trains, and evaluates a TensorFlow/Keras Deep Learning 
    Autoencoder to detect refrigerator temperature anomalies. 
    
    CONCEPTUAL EXPLANATIONS FOR BEGINNERS:
    ---------------------------------------------------------------------------
    1. WHAT IS AN AUTOENCODER?
       An Autoencoder is a type of Deep Neural Network trained to copy its input
       to its output. It compresses data into a lower dimension and then 
       reconstructs it back.

    2. ENCODER & DECODER:
       - ENCODER: Compresses the 10-reading input sequence into a small hidden
         representation (bottleneck of size 8).
       - DECODER: Reconstructs the original 10-reading sequence from that small
         bottleneck representation.

    3. RECONSTRUCTION & RECONSTRUCTION ERROR:
       - RECONSTRUCTION: The output sequence generated by the network.
       - RECONSTRUCTION ERROR: The difference (Mean Squared Error) between the 
         original temperature pattern and the Autoencoder's reconstructed output.

    4. WHY TRAIN ONLY ON NORMAL DATA?
       By training strictly on NORMAL operating data, the Autoencoder learns how
       refrigerator temperature behaves when everything is working fine. When an 
       UNSEEN ANOMALY occurs, the Autoencoder fails to reconstruct it accurately,
       resulting in a high reconstruction error!

    5. ANOMALY THRESHOLD:
       A cutoff error value (Mean + 3 * Std Deviation of normal training error).
       If a sequence's reconstruction error > Threshold, it is flagged as an ANOMALY.
===============================================================================
"""

import os
import sys
import joblib
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

# Silence TensorFlow verbose C++ logs
os.environ["TF_CPP_MIN_LOG_LEVEL"] = "2"

import tensorflow as tf
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import confusion_matrix, precision_score, recall_score, f1_score

# Define File Paths
PROCESSED_DATASET_PATH = os.path.join("dataset", "processed_temperature_data.csv")
MODEL_SAVE_PATH = os.path.join("model", "autoencoder.keras")
SCALER_SAVE_PATH = os.path.join("model", "scaler.pkl")
PREDICTIONS_CSV_PATH = os.path.join("results", "anomaly_predictions.csv")
PLOT_OUTPUT_PATH = os.path.join("results", "autoencoder_reconstruction_and_anomalies.png")

# Configuration
WINDOW_SIZE = 10  # Number of consecutive 5-minute readings per sequence
EPOCHS = 40
BATCH_SIZE = 32
RANDOM_SEED = 42

# Set random seeds for reproducibility
np.random.seed(RANDOM_SEED)
tf.random.set_seed(RANDOM_SEED)


def load_processed_data(file_path):
    """Step 1: Load preprocessed temperature dataset."""
    print("=" * 70)
    print("STEP 1: LOADING PROCESSED DATASET")
    print("=" * 70)
    
    if not os.path.exists(file_path):
        print(f"[!] File not found: '{file_path}'. Run preprocessing.py first!")
        sys.exit(1)

    df = pd.read_csv(file_path)
    df["timestamp"] = pd.to_datetime(df["timestamp"])
    print(f"[OK] Successfully loaded '{file_path}' with {len(df)} records.")
    return df


def prepare_sequences(df, window_size=10):
    """
    Steps 2, 3, & 4: Scale features and convert time-series into sliding window sequences.
    """
    print("\n" + "=" * 70)
    print("STEPS 2, 3, & 4: FEATURE SCALING & SLIDING WINDOW PREPARATION")
    print("=" * 70)

    # Scale temperatures to range [0, 1] for stable neural network training
    scaler = MinMaxScaler(feature_range=(0, 1))
    scaled_temp = scaler.fit_transform(df[["temperature"]]).flatten()

    sequences = []
    metadata = []  # Holds corresponding target timestamp, temperature, and reference status

    for i in range(len(scaled_temp) - window_size + 1):
        window = scaled_temp[i : i + window_size]
        sequences.append(window)

        # Use the timestamp and status of the last reading in the window as target
        target_idx = i + window_size - 1
        metadata.append({
            "timestamp": df["timestamp"].iloc[target_idx],
            "actual_temperature": df["temperature"].iloc[target_idx],
            "reference_status": df["status"].iloc[target_idx],
            "reference_is_anomaly": df["is_anomaly"].iloc[target_idx]
        })

    sequences = np.array(sequences)
    meta_df = pd.DataFrame(metadata)

    print(f"[+] Total Sliding Window Sequences Created: {sequences.shape[0]}")
    print(f"[+] Sequence Shape per Sample            : ({window_size},)")

    # Separate Normal sequences for training
    # A sequence is normal if its target reference status is 'Normal'
    normal_mask = (meta_df["reference_status"] == "Normal").values
    X_train_normal = sequences[normal_mask]

    print(f"[+] Normal Sequences Reserved for Training : {X_train_normal.shape[0]}")
    print(f"[+] Abnormal Sequences Reserved for Testing: {(~normal_mask).sum()}")

    return sequences, X_train_normal, meta_df, scaler


def build_autoencoder(input_dim=10):
    """
    Step 5: Build a Keras Deep Learning Autoencoder.
    Architecture:
        Input (10) -> Dense(16, ReLU) -> Dense(8, Bottleneck) -> Dense(16, ReLU) -> Output (10)
    """
    print("\n" + "=" * 70)
    print("STEP 5: BUILDING AUTOENCODER NEURAL NETWORK ARCHITECTURE")
    print("=" * 70)

    model = tf.keras.Sequential([
        tf.keras.layers.Input(shape=(input_dim,), name="input_sequence"),
        tf.keras.layers.Dense(16, activation="relu", name="encoder_layer1"),
        tf.keras.layers.Dense(8, activation="relu", name="encoder_bottleneck"),
        tf.keras.layers.Dense(16, activation="relu", name="decoder_layer1"),
        tf.keras.layers.Dense(input_dim, activation="linear", name="output_reconstruction")
    ], name="Refrigerator_Temperature_Autoencoder")

    model.compile(optimizer="adam", loss="mse")
    
    print("[+] Model Summary:")
    model.summary()
    return model


def train_autoencoder(model, X_train_normal):
    """
    Step 6: Train the Autoencoder using ONLY Normal sequences.
    """
    print("\n" + "=" * 70)
    print("STEP 6: TRAINING AUTOENCODER ON NORMAL DATA ONLY")
    print("=" * 70)
    print(f"[+] Training for {EPOCHS} epochs with batch size {BATCH_SIZE}...")

    history = model.fit(
        X_train_normal, X_train_normal,
        epochs=EPOCHS,
        batch_size=BATCH_SIZE,
        validation_split=0.1,
        verbose=0
    )

    final_loss = history.history["loss"][-1]
    final_val_loss = history.history["val_loss"][-1]
    print(f"[OK] Training Completed. Final Loss: {final_loss:.6f} | Val Loss: {final_val_loss:.6f}")
    return history


def calculate_reconstruction_error_and_threshold(model, X_train_normal, X_all_sequences):
    """
    Steps 7, 8, & 9: Calculate reconstruction errors and derive the anomaly threshold.
    """
    print("\n" + "=" * 70)
    print("STEPS 7, 8, & 9: RECONSTRUCTION ERROR & THRESHOLD CALCULATION")
    print("=" * 70)

    # Reconstruct normal training sequences to set the baseline error
    X_train_pred = model.predict(X_train_normal, verbose=0)
    normal_errors = np.mean(np.square(X_train_normal - X_train_pred), axis=1)

    # Anomaly threshold = Mean + 3 * Std Deviation of Normal Training Reconstruction Errors
    mean_error = np.mean(normal_errors)
    std_error = np.std(normal_errors)
    threshold = mean_error + 3 * std_error

    print(f"[+] Normal Training Error Mean : {mean_error:.6f}")
    print(f"[+] Normal Training Error Std  : {std_error:.6f}")
    print(f"[OK] Calculated Anomaly Threshold (Mean + 3*Std): {threshold:.6f}")

    # Reconstruct ALL sequences to calculate error for the whole timeline
    X_all_pred = model.predict(X_all_sequences, verbose=0)
    all_reconstruction_errors = np.mean(np.square(X_all_sequences - X_all_pred), axis=1)

    return all_reconstruction_errors, threshold, X_all_pred


def evaluate_and_classify(all_errors, threshold, meta_df):
    """
    Steps 10, 11, & 12: Classify sequences and compute evaluation metrics.
    """
    print("\n" + "=" * 70)
    print("STEPS 10, 11, & 12: ANOMALY CLASSIFICATION & EVALUATION METRICS")
    print("=" * 70)

    # Predicted binary label: 1 if reconstruction error > threshold, else 0
    predicted_binary = (all_errors > threshold).astype(int)
    predicted_status = np.where(predicted_binary == 1, "Anomaly", "Normal")

    meta_df["reconstruction_error"] = all_errors
    meta_df["threshold"] = threshold
    meta_df["predicted_status"] = predicted_status
    meta_df["predicted_binary"] = predicted_binary

    # Ground truth reference (is_anomaly: 0 for Normal, 1 for Anomaly)
    y_true = meta_df["reference_is_anomaly"].values
    y_pred = predicted_binary

    # Compute confusion matrix and metrics
    cm = confusion_matrix(y_true, y_pred)
    tn, fp, fn, tp = cm.ravel()

    precision = precision_score(y_true, y_pred, zero_division=0)
    recall = recall_score(y_true, y_pred, zero_division=0)
    f1 = f1_score(y_true, y_pred, zero_division=0)

    num_normal_pred = (y_pred == 0).sum()
    num_anomaly_pred = (y_pred == 1).sum()

    print(f"[+] Normal Predictions  : {num_normal_pred}")
    print(f"[+] Anomaly Predictions : {num_anomaly_pred}")
    print(f"[+] Confusion Matrix    :\n"
          f"    - True Negatives  (TN - Normal as Normal)  : {tn}\n"
          f"    - False Positives (FP - Normal as Anomaly) : {fp}\n"
          f"    - False Negatives (FN - Anomaly as Normal) : {fn}\n"
          f"    - True Positives  (TP - Anomaly as Anomaly): {tp}")

    print(f"\n[+] Model Performance Metrics vs Reference Ground Truth:")
    print(f"    - Precision : {precision:.4f}")
    print(f"    - Recall    : {recall:.4f}")
    print(f"    - F1-Score  : {f1:.4f}")

    return meta_df, precision, recall, f1, num_normal_pred, num_anomaly_pred


def save_artifacts_and_predictions(model, scaler, meta_df):
    """
    Step 14: Save trained model, scaler, and predictions CSV.
    """
    print("\n" + "=" * 70)
    print("STEP 14: SAVING MODEL ARTIFACTS AND PREDICTIONS")
    print("=" * 70)

    os.makedirs("model", exist_ok=True)
    os.makedirs("results", exist_ok=True)

    # Save model
    model.save(MODEL_SAVE_PATH)
    print(f"[OK] Trained Autoencoder saved to : '{MODEL_SAVE_PATH}'")

    # Save scaler
    joblib.dump(scaler, SCALER_SAVE_PATH)
    print(f"[OK] MinMaxScaler object saved to   : '{SCALER_SAVE_PATH}'")

    # Save predictions CSV
    output_cols = ["timestamp", "actual_temperature", "reference_status", 
                   "reconstruction_error", "threshold", "predicted_status"]
    meta_df[output_cols].to_csv(PREDICTIONS_CSV_PATH, index=False)
    print(f"[OK] Predictions CSV saved to       : '{PREDICTIONS_CSV_PATH}'")


def plot_autoencoder_results(meta_df, threshold, output_path):
    """
    Step 13: Plot original vs reconstructed temperature & reconstruction errors over time.
    """
    print("\n" + "=" * 70)
    print("STEP 13: GENERATING & SAVING VISUALIZATION PLOTS")
    print("=" * 70)

    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(14, 10), sharex=True)

    # -------------------------------------------------------------------------
    # Plot 1: Temperature Timeline & Autoencoder Predictions
    # -------------------------------------------------------------------------
    ax1.plot(meta_df["timestamp"], meta_df["actual_temperature"], 
             color="#1f77b4", linewidth=1.0, alpha=0.8, label="Actual Temperature (deg C)")
    
    anomalies = meta_df[meta_df["predicted_status"] == "Anomaly"]
    ax1.scatter(anomalies["timestamp"], anomalies["actual_temperature"], 
                color="red", s=15, label="Autoencoder Detected Anomalies", zorder=4)

    ax1.axhline(y=5.0, color="orange", linestyle="--", linewidth=1.0, label="Safe Limit High (5 deg C)")
    ax1.axhline(y=2.0, color="cyan", linestyle="--", linewidth=1.0, label="Safe Limit Low (2 deg C)")
    
    ax1.set_title("Autoencoder Anomaly Detection: Temperature Timeline", fontsize=13, fontweight="bold")
    ax1.set_ylabel("Temperature (deg C)", fontsize=11)
    ax1.grid(True, linestyle=":", alpha=0.6)
    ax1.legend(loc="upper right", frameon=True, facecolor="white")

    # -------------------------------------------------------------------------
    # Plot 2: Reconstruction Error over Time vs Threshold
    # -------------------------------------------------------------------------
    ax2.plot(meta_df["timestamp"], meta_df["reconstruction_error"], 
             color="#7f7f7f", linewidth=0.8, alpha=0.7, label="Reconstruction Error (MSE)")
    
    ax2.axhline(y=threshold, color="red", linestyle="--", linewidth=1.5, 
                label=f"Anomaly Threshold ({threshold:.5f})")

    ax2.scatter(anomalies["timestamp"], anomalies["reconstruction_error"], 
                color="red", s=15, label="High Error Anomalies (> Threshold)", zorder=4)

    ax2.set_title("Autoencoder Reconstruction Error vs. Learned Threshold", fontsize=13, fontweight="bold")
    ax2.set_xlabel("Timestamp (Date & Time)", fontsize=11)
    ax2.set_ylabel("Reconstruction Error (MSE)", fontsize=11)
    ax2.grid(True, linestyle=":", alpha=0.6)
    ax2.legend(loc="upper right", frameon=True, facecolor="white")

    plt.tight_layout()
    plt.savefig(output_path, dpi=300)
    plt.close()

    print(f"[OK] Visualization plots successfully saved to: '{output_path}'")


def main():
    print("\n" + "*" * 70)
    print(" SMART REFRIGERATOR ANOMALY DETECTION - PHASE 3: AUTOENCODER MODEL ")
    print("*" * 70 + "\n")

    # Step 1: Load preprocessed dataset
    df = load_processed_data(PROCESSED_DATASET_PATH)

    # Steps 2, 3, 4: Scale data and generate sliding windows
    sequences, X_train_normal, meta_df, scaler = prepare_sequences(df, window_size=WINDOW_SIZE)

    # Step 5: Build Autoencoder
    model = build_autoencoder(input_dim=WINDOW_SIZE)

    # Step 6: Train Autoencoder on Normal sequences
    train_autoencoder(model, X_train_normal)

    # Steps 7, 8, 9: Calculate reconstruction errors and threshold
    all_errors, threshold, X_all_pred = calculate_reconstruction_error_and_threshold(
        model, X_train_normal, sequences
    )

    # Steps 10, 11, 12: Classify and evaluate predictions
    meta_df, precision, recall, f1, num_normal_pred, num_anomaly_pred = evaluate_and_classify(
        all_errors, threshold, meta_df
    )

    # Step 14: Save trained model, scaler, and predictions CSV
    save_artifacts_and_predictions(model, scaler, meta_df)

    # Step 13: Plot and save visualizations
    plot_autoencoder_results(meta_df, threshold, PLOT_OUTPUT_PATH)

    # Step 17: Print required final summary
    print("\n" + "=" * 70)
    print("Autoencoder Training Completed")
    print("=" * 70)
    print(f"Training samples   : {len(X_train_normal)}")
    print(f"Normal samples     : {num_normal_pred}")
    print(f"Detected anomalies : {num_anomaly_pred}")
    print(f"Anomaly threshold  : {threshold:.6f}")
    print(f"Precision          : {precision:.4f}")
    print(f"Recall             : {recall:.4f}")
    print(f"F1-score           : {f1:.4f}")
    print("=" * 70)
    print("\n[!] DISCLAIMER: This model is a software-based educational prototype.")
    print("[!] Simple rule-based reference labels (2 deg C - 8 deg C) are distinct from the Autoencoder's learned error threshold.")
    print("[!] This model is not scientifically validated or intended for medical/production use.\n")


if __name__ == "__main__":
    main()
